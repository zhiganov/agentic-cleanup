#!/usr/bin/env python3
"""Regression tests for the read-only WizTree outlier finder."""

from __future__ import annotations

import csv
import importlib.util
import json
import subprocess
import sys
import tempfile
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[3]
HELPER_PATH = REPO_ROOT / "scripts" / "windows" / "cleanup" / "find_outliers.py"
spec = importlib.util.spec_from_file_location("find_outliers", HELPER_PATH)
assert spec and spec.loader
module = importlib.util.module_from_spec(spec)
sys.modules[spec.name] = module
spec.loader.exec_module(module)


def assert_true(condition: bool, message: str) -> None:
    if not condition:
        raise AssertionError(f"FAIL: {message}")
    print(f"PASS: {message}")


def add_tree(rows: list[tuple[str, int]], path: str, size_mb: int) -> None:
    rows.append((path, size_mb * module.MIB))


with tempfile.TemporaryDirectory(prefix="cleanup-outlier-test-") as temp:
    fixture = Path(temp) / "wiztree.csv"
    rows: list[tuple[str, int]] = []
    add_tree(rows, "C:\\", 120_000)
    add_tree(rows, "C:\\hiberfil.sys", 6_500)
    add_tree(rows, "C:\\pagefile.sys", 15_000)
    add_tree(rows, "C:\\installer.exe", 500)
    add_tree(rows, "C:\\small.bin", 99)
    add_tree(rows, "C:\\Users", 45_000)
    add_tree(rows, "C:\\Users\\archive.zip", 400)
    add_tree(rows, "C:\\Users\\dev", 44_000)
    add_tree(rows, "C:\\Users\\dev\\.cache", 3_000)
    add_tree(rows, "C:\\Users\\dev\\.cache\\puppeteer", 2_700)
    add_tree(rows, "C:\\Users\\dev\\.cache\\puppeteer\\chrome", 1_300)
    add_tree(rows, "C:\\Users\\dev\\.cache\\puppeteer\\headless", 1_200)
    add_tree(rows, "C:\\Users\\dev\\workspace", 5_000)
    add_tree(rows, "C:\\Users\\dev\\workspace\\app", 4_800)
    add_tree(rows, "C:\\Users\\dev\\workspace\\app\\.next", 1_500)
    add_tree(rows, "C:\\Users\\dev\\workspace\\app\\.next\\cache", 1_350)
    add_tree(rows, "C:\\Users\\dev\\workspace\\app\\src", 2_900)
    add_tree(rows, "C:\\Users\\dev\\workspace\\app\\src\\fixture.bin", 2_850)
    add_tree(rows, "C:\\Windows", 35_000)
    add_tree(rows, "C:\\Windows\\large-report.dmp", 350)
    add_tree(rows, "C:\\Windows\\WinSxS", 12_000)
    add_tree(rows, "C:\\Windows\\WinSxS\\ManifestCache", 600)
    add_tree(rows, "D:\\", 10_000)
    add_tree(rows, "D:\\HIBERFIL.SYS", 6_500)
    add_tree(rows, "D:\\disk.vhdx", 3_000)
    with fixture.open("w", encoding="utf-8-sig", newline="") as handle:
        handle.write("Generated by WizTree\n")
        writer = csv.writer(handle)
        writer.writerow(["File Name", "Size", "Allocated", "Modified", "Attributes", "Files", "Folders"])
        for path, size in rows:
            writer.writerow([path, size, size, "", "", "", ""])

    entries = module.load_entries(str(fixture))
    hotspots = module.select_hotspots(entries, 100 * module.MIB, 0.80, 9)
    paths = [entry.path.casefold() for entry in hotspots]

    assert_true(not any("hiberfil.sys" in path for path in paths), "hiberfil.sys is never emitted")
    assert_true(not any(path in paths for path in ("c:\\", "d:\\")), "drive roots are not emitted as outliers")
    shallow_files = {
        "c:\\pagefile.sys", "c:\\installer.exe", "c:\\users\\archive.zip",
        "c:\\windows\\large-report.dmp", "d:\\disk.vhdx",
    }
    assert_true(shallow_files.issubset(paths), "large files at drive roots and shallow directory levels remain visible")
    assert_true(
        all(not entry.is_directory for entry in hotspots if entry.key in shallow_files),
        "shallow files retain their file classification",
    )
    assert_true("c:\\small.bin" not in paths, "small root files remain below the materiality threshold")
    assert_true("c:\\users" not in paths and "c:\\windows" not in paths, "shallow wrapper directories still expand into children")
    assert_true("c:\\users\\dev\\.cache\\puppeteer" in paths, "large cache family is surfaced below the generic cache root")
    assert_true("c:\\users\\dev\\workspace\\app\\.next" in paths, "build-output boundary is surfaced")
    assert_true("c:\\windows\\winsxs\\manifestcache" in paths, "large system descendants remain visible for classification")
    assert_true(all(entry.size >= 100 * module.MIB for entry in hotspots), "every hotspot meets the materiality threshold")
    assert_true(
        all(not (left != right and right.startswith(left.rstrip("\\") + "\\")) for left in paths for right in paths),
        "hotspots do not contain overlapping ancestors and descendants",
    )
    assert_true(
        [entry.size for entry in hotspots] == sorted((entry.size for entry in hotspots), reverse=True),
        "hotspots are sorted largest first",
    )
    result = subprocess.run(
        [sys.executable, str(HELPER_PATH), str(fixture), "--minimum-mb", "100", "--limit", "100"],
        check=True,
        capture_output=True,
        text=True,
        timeout=15,
    )
    assert_true("hiberfil.sys" not in result.stdout.casefold(), "CLI output cannot surface hiberfil.sys")
    assert_true("|C:\\Users\\dev\\.cache\\puppeteer" in result.stdout, "CLI emits the classified hotspot input format")
    assert_true("file|15000|C:\\pagefile.sys" in result.stdout, "default CLI reports large root files without --files")
    json_result = subprocess.run(
        [sys.executable, str(HELPER_PATH), str(fixture), "--minimum-mb", "100", "--limit", "2", "--json"],
        check=True,
        capture_output=True,
        text=True,
        timeout=15,
    )
    report = json.loads(json_result.stdout)
    assert_true(report["entries"][0]["path"] == "C:\\pagefile.sys", "JSON hotspot report includes the largest root file")
    assert_true(report["entries"][0]["kind"] == "file", "JSON root-file classification is preserved")
    assert_true(report["matchingEntries"] == len(hotspots), "JSON coverage counts include shallow files")
    assert_true(report["omittedMatches"] == len(hotspots) - 2, "JSON top-N omissions include shallow files")
    assert_true("hiberfil.sys" not in json_result.stdout.casefold(), "JSON output keeps hibernation files suppressed")

print("All cleanup outlier-finder tests passed.")
